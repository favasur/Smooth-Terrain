using System;
using System.Globalization;
using System.IO;
using System.Text;

namespace SmoothTerrain.Tools
{
    /// <summary>
    /// Generates the fillet OBJ mesh from <see cref="BezierProfile"/>, the same curve the mod
    /// uses for collision boxes. Run from the repository root:
    ///
    ///     dotnet run --project tools/FilletMeshGen -- assets/smoothterrain/shapes/block/terrain-fillet.obj
    ///
    /// Pass --check to verify that the committed mesh is up to date instead of writing it.
    ///
    /// Shape space is 0..16 block units, y up, x east, z south, matching the convention the
    /// game uses for .obj shapes (where 1 unit of block space is 1/16 of a block).
    /// The block is full height at the north edge (z = 0) and falls to zero at the south
    /// edge (z = 16); orientation is handled by rotateYByType in the block json.
    /// </summary>
    internal static class Program
    {
        private const int MeshSlices = 16;
        private const double Size = 16.0;

        private static int Main(string[] args)
        {
            bool check = false;
            string output = null;

            foreach (string arg in args)
            {
                if (arg == "--check") check = true;
                else output = arg;
            }

            if (output == null)
            {
                output = Path.Combine("assets", "smoothterrain", "shapes", "block", "terrain-fillet.obj");
            }

            string generated = Build();

            if (check)
            {
                if (!File.Exists(output))
                {
                    Console.Error.WriteLine("Missing mesh: " + output);
                    return 1;
                }

                string existing = File.ReadAllText(output).Replace("\r\n", "\n");
                if (existing != generated)
                {
                    Console.Error.WriteLine("Mesh is stale, regenerate with: dotnet run --project tools/FilletMeshGen");
                    return 1;
                }

                Console.WriteLine("Mesh is up to date: " + output);
                return 0;
            }

            string directory = Path.GetDirectoryName(Path.GetFullPath(output));
            if (!string.IsNullOrEmpty(directory)) Directory.CreateDirectory(directory);

            File.WriteAllText(output, generated, new UTF8Encoding(false));
            Console.WriteLine("Wrote " + output + " (" + generated.Split('\n').Length + " lines)");
            return 0;
        }

        /// <summary>Sagitta check of the sampled profile: the drawn mesh never leaves the analytic curve.</summary>
        private static double HeightAtZ(double z)
        {
            return Size * BezierProfile.Height(1.0 - z / Size);
        }

        private static string Build()
        {
            var sb = new StringBuilder();
            var verts = new StringBuilder();
            var uvs = new StringBuilder();
            var normals = new StringBuilder();
            var faces = new StringBuilder();

            int vertexIndex = 1;
            int uvIndex = 1;
            int normalIndex = 1;

            sb.AppendLine("# Terrain fillet mesh - generated, do not edit by hand.");
            sb.AppendLine("# Profile: cubic Bezier P0(0,0) P1(1/3,0) P2(2/3,1) P3(1,1) => h(u) = 3u^2 - 2u^3");
            sb.AppendLine("# Tangents are horizontal at u=0 and u=1, so the edge meets flat ground without a crease.");
            sb.AppendLine("# Shape space: 0..16 units, y up, x east, z south. Full height at north (z=0), zero at south.");
            sb.AppendLine("# Generated by tools/FilletMeshGen from src/BezierProfile.cs.");
            sb.AppendLine();

            for (int i = 0; i < MeshSlices; i++)
            {
                double z0 = i * Size / MeshSlices;
                double z1 = (i + 1) * Size / MeshSlices;
                double y0 = HeightAtZ(z0);
                double y1 = HeightAtZ(z1);

                // Top surface quad. Winding is counter-clockwise seen from above.
                AddQuad(
                    verts, uvs, normals, faces,
                    ref vertexIndex, ref uvIndex, ref normalIndex,
                    new V3(0, y0, z0), new V3(16, y1, z1), new V3(16, y1, z1), new V3(0, y1, z1),
                    NormalAtZ(z0), NormalAtZ(z1),
                    new Uv(0, z0 / Size), new Uv(0, z1 / Size), new Uv(1, z1 / Size), new Uv(1, z0 / Size),
                    "top");

                // East and west curtains under the curve.
                if (y0 > 0.0001 || y1 > 0.0001)
                {
                    AddQuad(
                        verts, uvs, normals, faces,
                        ref vertexIndex, ref uvIndex, ref normalIndex,
                        new V3(16, 0, z0), new V3(16, 0, z1), new V3(16, y1, z1), new V3(16, y0, z0),
                        new V3(1, 0, 0), new V3(1, 0, 0),
                        new Uv(z0 / Size, 0), new Uv(z1 / Size, 0), new Uv(z1 / Size, y1 / Size), new Uv(z0 / Size, y0 / Size),
                        "all");

                    AddQuad(
                        verts, uvs, normals, faces,
                        ref vertexIndex, ref uvIndex, ref normalIndex,
                        new V3(0, 0, z0), new V3(0, 0, z1), new V3(0, y1, z1), new V3(0, y0, z0),
                        new V3(-1, 0, 0), new V3(-1, 0, 0),
                        new Uv(z0 / Size, 0), new Uv(z1 / Size, 0), new Uv(z1 / Size, y1 / Size), new Uv(z0 / Size, y0 / Size),
                        "all");
                }
            }

            // North face: the full-height wall at z = 0.
            AddQuad(
                verts, uvs, normals, faces,
                ref vertexIndex, ref uvIndex, ref normalIndex,
                new V3(0, 0, 0), new V3(16, 0, 0), new V3(16, 16, 0), new V3(0, 16, 0),
                new V3(0, 0, -1), new V3(0, 0, -1),
                new Uv(0, 0), new Uv(1, 0), new Uv(1, 1), new Uv(0, 1),
                "all");

            // Bottom face at y = 0.
            AddQuad(
                verts, uvs, normals, faces,
                ref vertexIndex, ref uvIndex, ref normalIndex,
                new V3(0, 0, 0), new V3(16, 0, 0), new V3(16, 0, 16), new V3(0, 0, 16),
                new V3(0, -1, 0), new V3(0, -1, 0),
                new Uv(0, 0), new Uv(1, 0), new Uv(1, 1), new Uv(0, 1),
                "all");

            sb.Append(verts);
            sb.Append(uvs);
            sb.Append(normals);
            sb.Append(faces);

            return sb.ToString().Replace("\r\n", "\n");
        }

        private struct V3
        {
            public double X, Y, Z;
            public V3(double x, double y, double z) { X = x; Y = y; Z = z; }
        }

        private struct Uv
        {
            public double U, V;
            public Uv(double u, double v) { U = u; V = v; }
        }

        /// <summary>Outward normal of the top surface at z, from the analytic derivative.</summary>
        private static V3 NormalAtZ(double z)
        {
            double u = 1.0 - z / Size;
            double slope = 6.0 * u * (1.0 - u);
            double ny = 1.0;
            double nz = slope;
            double length = Math.Sqrt(ny * ny + nz * nz);
            return new V3(0, ny / length, nz / length);
        }

        /// <summary>
        /// Adds one quad with four vertices, four uvs and two distinct normals (the normal of
        /// the first edge is used for the first two vertices, the second for the last two).
        /// Vertex positions are converted from shape space to the unit-cube space used by .obj
        /// shapes: shape / 16 - 0.5.
        /// </summary>
        private static void AddQuad(
            StringBuilder verts,
            StringBuilder uvs,
            StringBuilder normals,
            StringBuilder faces,
            ref int vertexIndex,
            ref int uvIndex,
            ref int normalIndex,
            V3 a,
            V3 b,
            V3 c,
            V3 d,
            V3 n0,
            V3 n1,
            Uv ua,
            Uv ub,
            Uv uc,
            Uv ud,
            string material)
        {
            V3[] points = { a, b, c, d };
            Uv[] texcoords = { ua, ub, uc, ud };
            V3[] faceNormals = { n0, n0, n1, n1 };

            for (int i = 0; i < 4; i++)
            {
                verts.Append("v ")
                     .Append(F(points[i].X / Size - 0.5)).Append(' ')
                     .Append(F(points[i].Y / Size - 0.5)).Append(' ')
                     .Append(F(points[i].Z / Size - 0.5)).Append('\n');

                uvs.Append("vt ").Append(F(texcoords[i].U)).Append(' ').Append(F(texcoords[i].V)).Append('\n');

                normals.Append("vn ")
                       .Append(F(faceNormals[i].X)).Append(' ')
                       .Append(F(faceNormals[i].Y)).Append(' ')
                       .Append(F(faceNormals[i].Z)).Append('\n');
            }

            faces.Append("usemtl ").Append(material).Append('\n');
            faces.Append("f ")
                 .Append(vertexIndex).Append('/').Append(uvIndex).Append('/').Append(normalIndex).Append(' ')
                 .Append(vertexIndex + 1).Append('/').Append(uvIndex + 1).Append('/').Append(normalIndex + 1).Append(' ')
                 .Append(vertexIndex + 2).Append('/').Append(uvIndex + 2).Append('/').Append(normalIndex + 2).Append(' ')
                 .Append(vertexIndex + 3).Append('/').Append(uvIndex + 3).Append('/').Append(normalIndex + 3)
                 .Append('\n');

            vertexIndex += 4;
            uvIndex += 4;
            normalIndex += 4;
        }

        private static string F(double value)
        {
            return value.ToString("0.000000", CultureInfo.InvariantCulture);
        }
    }
}
